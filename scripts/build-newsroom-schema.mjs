import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const directory = fileURLToPath(new URL('../news-app/supabase/', import.meta.url))
const migrations = (await readdir(path.join(directory, 'migrations'))).filter(name => name.endsWith('.sql')).sort()
const sources = ['schema-base.sql', ...migrations.map(name => `migrations/${name}`)]
const parts = await Promise.all(sources.map(async name => `\n-- Source: ${name}\n${await readFile(path.join(directory, name), 'utf8')}`))
const output = '-- GENERATED by scripts/build-newsroom-schema.mjs; edit the base or add a migration.\n'
  + '-- Fresh projects: run this entire file. Existing projects: apply new migrations only.\n'
  + '-- Includes the original schema and every migration, in order.\n' + parts.join('\n')
const target = path.join(directory, 'schema.sql')
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Newsroom schema is stale. Run npm run prepare:schema.')
  console.log(`Newsroom bootstrap matches the base and ${migrations.length} migrations.`)
} else {
  await writeFile(target, output)
  console.log(`Generated newsroom bootstrap with ${migrations.length} migrations.`)
}
